const STATUS_ALIASES = {
  p: "present",
  present: "present",
  a: "absent",
  absent: "absent",
  l: "leave",
  leave: "leave",
  onleave: "leave",
  on_leave: "leave",
  cl: "leave",
  casual: "leave",
  sl: "leave",
  sick: "leave",
  spl: "leave",
  special: "leave",
  od: "leave",
  on_duty: "leave",
};

const normalizeStatus = (rawStatus) => {
  const value = String(rawStatus || "")
    .trim()
    .toLowerCase();
  return STATUS_ALIASES[value] || value;
};

const normalizeDate = (value) => {
  if (!value) return null;
  if (typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value))
    return value;
  try {
    const dateObj =
      typeof value === "string" && value.includes("T")
        ? parseISO(value)
        : new Date(value);
    if (Number.isNaN(dateObj.getTime())) return null;
    return format(dateObj, "yyyy-MM-dd");
  } catch {
    return null;
  }
};

const isSecondOrFourthSaturday = (dateObj) => {
  if (dateObj.getDay() !== 6) return false;
  const weekNumber = Math.ceil(dateObj.getDate() / 7);
  return weekNumber === 2 || weekNumber === 4;
};

const normalizeAttendanceData = (records = []) => {
  const byDate = new Map();
  const invalid = [];

  records.forEach((record) => {
    const date = normalizeDate(record?.date);
    const rawVal = record?.attendanceStatus || record?.status;
    const status = normalizeStatus(rawVal);
    if (!date || !["present", "absent", "leave"].includes(status)) {
      invalid.push(record);
      return;
    }

    const rawStatusLower = String(record?.status || "").toLowerCase();
    const rawAttLower = String(record?.attendanceStatus || "").toLowerCase();
    let leaveType = record?.leaveType || null;
    if (!leaveType) {
      if (["cl", "casual"].includes(rawStatusLower) || ["cl", "casual"].includes(rawAttLower)) leaveType = "CASUAL";
      else if (["sl", "sick"].includes(rawStatusLower) || ["sl", "sick"].includes(rawAttLower)) leaveType = "SICK";
      else if (["spl", "special"].includes(rawStatusLower) || ["spl", "special"].includes(rawAttLower)) leaveType = "SPECIAL";
      else if (["od", "on_duty"].includes(rawStatusLower) || ["od", "on_duty"].includes(rawAttLower)) leaveType = "ON_DUTY";
    }

    const normalized = {
      ...record,
      date,
      status,
      leaveType,
      rawStatus: record?.status,
      verificationStatus: record?.verificationStatus || "VERIFIED",
      verifiedBy: record?.verifiedBy || null,
      verifiedAt: record?.verifiedAt || null,
      rejectionReason: record?.rejectionReason || null,
      markedAt: record?.markedAt || null,
    };

    const current = byDate.get(date);
    if (!current) {
      byDate.set(date, normalized);
      return;
    }

    const currentTs = new Date(
      current?.$updatedAt || current?.markedAt || current?.$createdAt || 0,
    ).getTime();
    const candidateTs = new Date(
      normalized?.$updatedAt ||
        normalized?.markedAt ||
        normalized?.$createdAt ||
        0,
    ).getTime();
    if (candidateTs >= currentTs) byDate.set(date, normalized);
  });

  return { byDate, records: Array.from(byDate.values()), invalid };
};

const generateWorkingDays = ({ startDate, endDate, holidaysMap }) => {
  if (!startDate || !endDate || startDate > endDate) return [];
  return eachDayOfInterval({ start: startDate, end: endDate })
    .map((dateObj) => ({ dateObj, date: format(dateObj, "yyyy-MM-dd") }))
    .filter(({ dateObj, date }) => {
      if (holidaysMap.has(date)) return false;
      if (dateObj.getDay() === 0) return false;
      if (isSecondOrFourthSaturday(dateObj)) return false;
      return true;
    })
    .map(({ date }) => date);
};

const buildAttendanceMap = ({
  workingDaysList,
  attendanceByDate,
  profile,
  batchId,
}) => {
  const finalMap = new Map();
  workingDaysList.forEach((date) => {
    const existing = attendanceByDate.get(date);
    if (existing) {
      finalMap.set(date, { ...existing, autoGenerated: false });
      return;
    }
    finalMap.set(date, {
      userId: profile?.userId || null,
      batchId: batchId || null,
      tradeId: profile?.tradeId || null,
      date,
      status: "absent",
      markedAt: null,
      remarks: "Auto-marked absent (no record)",
      autoGenerated: true,
    });
  });
  return finalMap;
};

const calculateStats = (records = [], holidayDays = 0) => {
  let presentDays = 0;
  let absentDays = 0;
  let leaveDays = 0;
  let casualLeaves = 0;
  let sickLeaves = 0;
  let specialLeaves = 0;

  records.forEach((record) => {
    // Skip unverified pending records from student statistics calculation
    if (record?.verificationStatus === "PENDING") return;

    const st = record.attendanceStatus ? record.attendanceStatus.toLowerCase() : record.status;
    const lt = String(record.leaveType || "").toUpperCase();
    if (st === "present" || st === "p") {
      presentDays += 1;
    } else if (st === "leave" || lt) {
      leaveDays += 1;
      if (lt === "CASUAL") casualLeaves += 1;
      else if (lt === "SICK") sickLeaves += 1;
      else if (lt === "SPECIAL") specialLeaves += 1;
    } else if (st === "absent" || st === "a") {
      absentDays += 1;
    }
  });

  const totalDays = presentDays + absentDays;
  return {
    totalDays,
    presentDays,
    absentDays,
    leaveDays,
    casualLeaves,
    sickLeaves,
    specialLeaves,
    holidayDays,
    attendancePercentage:
      totalDays > 0 ? Number(((presentDays / totalDays) * 100).toFixed(2)) : 0,
  };
};

const toMinutes = (time, fallback) => {
  const [h, m] = String(time || fallback)
    .split(":")
    .map((v) => Number(v || 0));
  return h * 60 + m;
};

export const useStudentAttendance = (profile) => {
  const activeBatchId = useSelector(selectActiveBatchId);
  const resolvedBatchId = activeBatchId;
  const isResolvingBatch = !activeBatchId && !!profile?.userId;

  // batchData already lives in Redux (activeBatchSlice fetches it on init)
  // — reading it here costs zero extra network calls
  const batchData = useSelector(selectActiveBatchData);
  const tradeId = batchData?.tradeId?.$id || batchData?.tradeId;
  const { data: tradeData = null } = useGetTradeQuery(tradeId, { skip: !tradeId });

  const [isLoadingAttendance, setIsLoadingAttendance] = useState(false);
  const [isLoadingOverallStats, setIsLoadingOverallStats] = useState(false);
  const [rawMonthlyRecords, setRawMonthlyRecords] = useState([]);
  const [holidays, setHolidays] = useState(new Map());
  const [invalidRecords, setInvalidRecords] = useState([]);
  const [currentMonth, setCurrentMonth] = useState(
    format(new Date(), "MMMM yyyy"),
  );
  const [selectedDate, setSelectedDate] = useState(new Date());
  const [lastUpdatedDate, setLastUpdatedDate] = useState(null);
  const [overallStats, setOverallStats] = useState(null);

  // ── Per-student enrollment date from batchStudents record ──────────────
  // This is the authoritative lower bound for working days, stats, and
  // attendance blocking. It lives in the batchStudents table, NOT on the
  // profile, because a student can have different enrollment dates per batch.
  const [enrollmentDate, setEnrollmentDate] = useState(null);
  const [isLoadingEnrollment, setIsLoadingEnrollment] = useState(false);

  useEffect(() => {
    if (!resolvedBatchId || !profile?.userId) return;
    let cancelled = false;
    setIsLoadingEnrollment(true);
    batchStudentService
      .getStudentRecord(resolvedBatchId, profile.userId)
      .then((record) => {
        if (cancelled) return;
        // enrollmentDate is stored as ISO string in batchStudents
        const raw = record?.enrollmentDate ?? record?.joinedAt ?? null;
        setEnrollmentDate(raw ? normalizeDate(raw) : null);
      })
      .catch(() => {
        if (!cancelled) setEnrollmentDate(null);
      })
      .finally(() => {
        if (!cancelled) setIsLoadingEnrollment(false);
      });
    return () => { cancelled = true; };
  }, [resolvedBatchId, profile?.userId]);

  // Effective start date: student's enrollment date (or batch start as fallback)
  const effectiveStartDate = useMemo(
    () => enrollmentDate ?? normalizeDate(batchData?.start_date) ?? null,
    [enrollmentDate, batchData?.start_date],
  );

  // ── Annual Leave Quotas (CL max 12/yr, SL max 15d/yr) ───────────────────
  const currentYear = useMemo(() => new Date().getFullYear(), []);
  const [annualLeaveRecords, setAnnualLeaveRecords] = useState([]);

  const fetchAnnualLeaves = useCallback(async () => {
    if (!profile?.userId || !resolvedBatchId) return;
    try {
      const startOfYear = `${currentYear}-01-01`;
      const endOfYear = `${currentYear}-12-31`;
      const res = await newAttendanceService.getStudentAttendanceByDateRange(
        profile.userId,
        resolvedBatchId,
        startOfYear,
        endOfYear,
      );
      setAnnualLeaveRecords(res?.documents || (Array.isArray(res) ? res : []));
    } catch (err) {
      console.error("Error fetching annual leaves:", err);
      setAnnualLeaveRecords([]);
    }
  }, [profile?.userId, resolvedBatchId, currentYear]);

  useEffect(() => {
    fetchAnnualLeaves();
  }, [fetchAnnualLeaves]);

  const leaveQuota = useMemo(() => {
    let clUsed = 0;
    let clPending = 0;
    let slDaysUsed = 0;
    let slDaysPending = 0;
    let splUsed = 0;
    const sickDates = [];

    const records = Array.isArray(annualLeaveRecords)
      ? annualLeaveRecords
      : (annualLeaveRecords?.documents || []);

    records.forEach((r) => {
      const statusLower = String(r.status || "").toLowerCase();
      const attLower = String(r.attendanceStatus || "").toLowerCase();
      const lt = String(r.leaveType || "").toUpperCase();
      const isLeave = attLower === "leave" || ["casual", "cl", "sick", "sl", "special", "spl"].includes(statusLower);
      if (!isLeave) return;

      const isPending = r.verificationStatus === "PENDING";
      const isRejected = r.verificationStatus === "REJECTED";
      if (isRejected) return;

      const isCasual = lt === "CASUAL" || ["casual", "cl"].includes(statusLower);
      const isSick = lt === "SICK" || ["sick", "sl"].includes(statusLower);
      const isSpecial = lt === "SPECIAL" || ["special", "spl"].includes(statusLower);

      if (isCasual) {
        if (isPending) clPending += 1;
        else clUsed += 1;
      } else if (isSick) {
        if (isPending) {
          slDaysPending += 1;
        } else {
          slDaysUsed += 1;
          if (r.date) sickDates.push(r.date);
        }
      } else if (isSpecial) {
        splUsed += 1;
      }
    });

    let slSpellsUsed = 0;
    if (sickDates.length > 0) {
      const sorted = [...sickDates].sort();
      slSpellsUsed = 1;
      for (let i = 1; i < sorted.length; i++) {
        const diff = Math.round((new Date(sorted[i]) - new Date(sorted[i - 1])) / (1000 * 60 * 60 * 24));
        if (diff > 1) slSpellsUsed += 1;
      }
    }

    const clRemaining = Math.max(0, 12 - (clUsed + clPending));
    const slDaysRemaining = Math.max(0, 15 - (slDaysUsed + slDaysPending));
    const slSpellsRemaining = Math.max(0, 2 - slSpellsUsed);

    return {
      clTotal: 12,
      clUsed,
      clPending,
      clRemaining,
      slTotalDays: 15,
      slDaysUsed,
      slDaysPending,
      slDaysRemaining,
      slMaxSpells: 2,
      slSpellsUsed,
      slSpellsRemaining,
      splUsed,
      isClExceeded: (clUsed + clPending) >= 12,
      isSlDaysExceeded: (slDaysUsed + slDaysPending) >= 15,
      isSlSpellsExceeded: slSpellsUsed >= 2,
    };
  }, [annualLeaveRecords]);

  const getMonthRange = useCallback((monthLabel) => {
    const parsedDate = parse(monthLabel, "MMMM yyyy", new Date());
    return { start: startOfMonth(parsedDate), end: endOfMonth(parsedDate) };
  }, []);

  const fetchMonthlyAttendance = useCallback(async () => {
    if (!resolvedBatchId || !profile?.userId) return;
    setIsLoadingAttendance(true);
    try {
      const { start, end } = getMonthRange(currentMonth);

      // Use enrollment date as the lower bound, not batch start_date
      const effectiveStart = effectiveStartDate
        ? startOfDay(new Date(effectiveStartDate))
        : (batchData?.start_date ? startOfDay(new Date(batchData.start_date)) : start);

      const batchEnd = batchData?.end_date
        ? endOfDay(new Date(batchData.end_date))
        : endOfDay(end);

      const rangeStart = new Date(
        Math.max(start.getTime(), effectiveStart.getTime()),
      );
      const rangeEnd = new Date(
        Math.min(
          endOfDay(end).getTime(),
          batchEnd.getTime()
        ),
      );

      const startDate = format(rangeStart, "yyyy-MM-dd");
      const endDate = format(rangeEnd, "yyyy-MM-dd");

      const [attendanceRes, holidayRes] = await Promise.all([
        newAttendanceService.getStudentAttendanceByDateRange(
          profile.userId,
          resolvedBatchId,
          startDate,
          endDate,
        ),
        holidayService.getBatchHolidaysByDateRange(
          resolvedBatchId,
          startDate,
          endDate,
        ),
      ]);

      setRawMonthlyRecords(attendanceRes?.documents || []);
      const holidayMap = new Map();
      (holidayRes || []).forEach((item) => {
        const date = normalizeDate(item?.date);
        if (!date) return;
        if (date > endDate || date < startDate) return;
        holidayMap.set(date, String(item?.holidayText || "Holiday").trim());
      });
      setHolidays(holidayMap);
    } catch (error) {
      console.log(error);
      toast.error("Failed to fetch attendance.");
    } finally {
      setIsLoadingAttendance(false);
    }
  }, [profile, currentMonth, getMonthRange, batchData, resolvedBatchId, effectiveStartDate]);

  useEffect(() => {
    fetchMonthlyAttendance();
  }, [fetchMonthlyAttendance]);

  const fetchOverallStats = useCallback(async () => {
    if (!profile?.userId || !resolvedBatchId) return;
    setIsLoadingOverallStats(true);
    try {
      // Historical Overall = From student's enrollment date up to end of previous month.
      // Using currentMonth (not selectedDate) so clicking individual dates within
      // the same month does NOT re-trigger this fetch.

      // Use enrollment date as the per-student lower bound
      const effectiveStart = effectiveStartDate ?? (batchData?.start_date || null);

      const currentMonthDate = parse(currentMonth, "MMMM yyyy", new Date());
      const prevMonthEnd = format(endOfMonth(subMonths(currentMonthDate, 1)), "yyyy-MM-dd");

      const stats = await newAttendanceService.getStudentAttendanceStats(
        profile.userId,
        resolvedBatchId,
        effectiveStart,   // ← uses enrollment date, not batch start
        prevMonthEnd
      );
      setOverallStats({
        totalDays: stats.total,
        presentDays: stats.presentDays,
        absentDays: stats.absentDays,
        attendancePercentage: stats.percentage,
        leaveDays: 0,
        workingDays: stats.total,
      });
    } catch (error) {
      console.error("Error fetching overall stats:", error);
    } finally {
      setIsLoadingOverallStats(false);
    }
  }, [profile, resolvedBatchId, effectiveStartDate, currentMonth]);

  useEffect(() => {
    fetchOverallStats();
  }, [fetchOverallStats]);

  const normalized = useMemo(
    () => normalizeAttendanceData(rawMonthlyRecords),
    [rawMonthlyRecords],
  );

  useEffect(() => {
    setInvalidRecords(normalized.invalid);
  }, [normalized.invalid]);

  const workingDaysList = useMemo(() => {
    // Use student's enrollment date as lower bound (not batch start_date)
    if (!effectiveStartDate) return [];

    const { start: monthStart, end: monthEnd } = getMonthRange(currentMonth);
    const enrollStart = startOfDay(new Date(effectiveStartDate));
    const batchEnd = batchData?.end_date
      ? endOfDay(new Date(batchData.end_date))
      : monthEnd;

    const rangeStart = new Date(
      Math.max(monthStart.getTime(), enrollStart.getTime()),
    );
    const rangeEnd = new Date(
      Math.min(monthEnd.getTime(), batchEnd.getTime()),
    );

    return generateWorkingDays({
      startDate: rangeStart,
      endDate: rangeEnd,
      holidaysMap: holidays,
    });
  }, [effectiveStartDate, batchData, currentMonth, getMonthRange, holidays]);

  const finalAttendanceMap = useMemo(
    () =>
      buildAttendanceMap({
        workingDaysList,
        attendanceByDate: normalized.byDate,
        profile,
        batchId: resolvedBatchId,
      }),
    [workingDaysList, normalized.byDate, profile, resolvedBatchId],
  );

  const finalAttendanceRecords = useMemo(
    () =>
      Array.from(finalAttendanceMap.values()).sort(
        (a, b) => new Date(b.date) - new Date(a.date),
      ),
    [finalAttendanceMap],
  );

  const stats = useMemo(() => {
    const todayStr = format(new Date(), "yyyy-MM-dd");
    const recordsUpToToday = finalAttendanceRecords.filter(r => r.date <= todayStr);
    return calculateStats(recordsUpToToday, holidays.size);
  }, [finalAttendanceRecords, holidays.size]);

  const studentAttendance = useMemo(
    () => ({
      ...profile,
      attendanceRecords: finalAttendanceRecords,
      batchId: resolvedBatchId,
    }),
    [profile, finalAttendanceRecords, resolvedBatchId],
  );

  const markAttendance = async (dateStr, status = "present", remarks = "") => {
    try {
      if (!batchData?.canMarkAttendance) {
        toast.warn("Attendance marking is disabled for this batch.");
        return null;
      }
      const normalizedDate = normalizeDate(dateStr);
      if (!normalizedDate) {
        toast.error("Invalid date.");
        return null;
      }

      const today = format(new Date(), "yyyy-MM-dd");
      if (normalizedDate > today) {
        toast.warn("Future dates cannot be marked.");
        return null;
      }
      if (normalizedDate < today && !batchData?.canMarkPrevious) {
        toast.warn("Past attendance marking is disabled.");
        return null;
      }
      if (holidays.has(normalizedDate)) {
        toast.warn("Cannot mark attendance on a holiday.");
        return null;
      }

      // Block attendance before student's own enrollment date (not just batch start)
      if (
        effectiveStartDate &&
        normalizedDate < effectiveStartDate
      ) {
        toast.warn("Cannot mark attendance before your enrollment date.");
        return null;
      }

      if (
        batchData?.end_date &&
        normalizedDate > normalizeDate(batchData.end_date)
      ) {
        toast.warn("Date is after batch end.");
        return null;
      }

      const nowMins = new Date().getHours() * 60 + new Date().getMinutes();
      const startMins = toMinutes(batchData?.attendanceTime?.start, "09:00");
      const endMins = toMinutes(batchData?.attendanceTime?.end, "18:00");
      if (
        normalizedDate === today &&
        (nowMins < startMins || nowMins > endMins)
      ) {
        toast.warn("Attendance can only be marked within attendance time.");
        return null;
      }

      const rawS = String(status || "").trim().toLowerCase();
      let statusToSave = "present";
      let attendanceStatusToSave = "PRESENT";
      let leaveTypeToSave = null;

      if (["cl", "casual"].includes(rawS)) {
        statusToSave = "casual";
        attendanceStatusToSave = "LEAVE";
        leaveTypeToSave = "CASUAL";
      } else if (["sl", "sick"].includes(rawS)) {
        statusToSave = "sick";
        attendanceStatusToSave = "LEAVE";
        leaveTypeToSave = "SICK";
      } else if (["spl", "special"].includes(rawS)) {
        statusToSave = "special";
        attendanceStatusToSave = "LEAVE";
        leaveTypeToSave = "SPECIAL";
      } else if (["absent", "a"].includes(rawS)) {
        statusToSave = "absent";
        attendanceStatusToSave = "ABSENT";
        leaveTypeToSave = null;
      }

      // Enforce annual leave quota limits (CL max 12, SL max 15 days)
      if (leaveTypeToSave === "CASUAL" && leaveQuota.clRemaining < 1) {
        toast.error(`Casual Leave quota exceeded. You have already used or requested all 12 days of CL for ${currentYear}.`);
        return null;
      }
      if (leaveTypeToSave === "SICK" && leaveQuota.slDaysRemaining < 1) {
        toast.error(`Sick Leave quota exceeded. You have already used or requested all 15 days of SL for ${currentYear}.`);
        return null;
      }

      let existing = normalized.byDate.get(normalizedDate);
      // Query DB if not in local month state to respect unique index idx_user_batch_date
      if (!existing) {
        try {
          existing = await newAttendanceService.getAttendanceByDate(profile?.userId, resolvedBatchId, normalizedDate);
        } catch {
          existing = null;
        }
      }
      const isPastDate = normalizedDate < today;

      // Check if existing record is already PENDING or REJECTED
      if (existing && !existing.autoGenerated) {
        if (existing.verificationStatus === "PENDING") {
          toast.info("A past attendance request for this date is already pending instructor verification.");
          return existing;
        }
        if (existing.verificationStatus === "REJECTED") {
          toast.error(`Your attendance request for this date was rejected: "${existing.rejectionReason || 'No reason provided'}". Contact instructor to change.`);
          return existing;
        }
        if (existing.status === statusToSave && existing.verificationStatus === "VERIFIED") {
          toast.info("Attendance already marked as " + statusToSave + ".");
          return existing;
        }
      }

      const targetVerificationStatus = isPastDate ? "PENDING" : "VERIFIED";

      let result;
      if (existing) {
        result = await newAttendanceService.updateAttendance(existing.$id, {
          status: statusToSave,
          attendanceStatus: attendanceStatusToSave,
          leaveType: leaveTypeToSave,
          remarks,
          markedBy: profile?.userId,
          verificationStatus: targetVerificationStatus,
          rejectionReason: null,
        });
      } else {
        result = await newAttendanceService.createAttendance({
          userId: profile?.userId,
          batchId: resolvedBatchId,
          tradeId: profile?.tradeId || null,
          date: normalizedDate,
          status: statusToSave,
          attendanceStatus: attendanceStatusToSave,
          leaveType: leaveTypeToSave,
          remarks,
          markedBy: profile?.userId,
          verificationStatus: targetVerificationStatus,
          rejectionReason: null,
        });
      }

      if (isPastDate) {
        toast.success("Past attendance request submitted! It will count in your stats once verified by your instructor.");
      }

      // Update only the changed date locally to avoid full-month refetch flicker.
      setRawMonthlyRecords((prev) => {
        const next = Array.isArray(prev) ? [...prev] : [];
        const idx = next.findIndex(
          (r) => normalizeDate(r?.date) === normalizedDate,
        );
        const merged = {
          ...(idx >= 0 ? next[idx] : {}),
          ...(result || {}),
          date: normalizedDate,
          status: statusToSave,
          attendanceStatus: attendanceStatusToSave,
          leaveType: leaveTypeToSave,
          remarks,
          markedBy: profile?.userId,
          verificationStatus: targetVerificationStatus,
          markedAt: result?.markedAt || new Date().toISOString(),
        };
        if (idx >= 0) next[idx] = merged;
        else next.push(merged);
        return next;
      });
      setLastUpdatedDate(normalizedDate);
      setTimeout(() => setLastUpdatedDate(null), 2200);

      // Persist attendance marked status locally & to SW cache for background notification silencing
      try {
        const todayStr = format(new Date(), "yyyy-MM-dd");
        if (normalizedDate === todayStr) {
          localStorage.setItem(`att_marked_${todayStr}_${profile?.userId}`, "true");
          if ("caches" in window) {
            caches.open("iti-sw-state").then((c) => {
              c.put(`att-marked-${todayStr}`, new Response("true")).catch(() => {});
            });
          }
        }
      } catch {
        // Safe ignore
      }

      fetchAnnualLeaves();
      toast.success("Attendance saved successfully!");
      return result;
    } catch (error) {
      console.error("Error marking attendance:", error);
      toast.error("Failed to mark attendance.");
      throw error;
    }
  };

  const markMultipleAttendance = async ({ dates = [], status = "present", remarks = "" }) => {
    try {
      if (!Array.isArray(dates) || dates.length === 0) {
        toast.warn("No dates provided to mark.");
        return null;
      }
      if (!batchData?.canMarkPrevious) {
        toast.warn("Past attendance marking is disabled for this batch.");
        return null;
      }

      const today = format(new Date(), "yyyy-MM-dd");
      const rawS = String(status || "").trim().toLowerCase();
      let statusToSave = "present";
      let attendanceStatusToSave = "PRESENT";
      let leaveTypeToSave = null;

      if (["cl", "casual"].includes(rawS)) {
        statusToSave = "casual";
        attendanceStatusToSave = "LEAVE";
        leaveTypeToSave = "CASUAL";
      } else if (["sl", "sick"].includes(rawS)) {
        statusToSave = "sick";
        attendanceStatusToSave = "LEAVE";
        leaveTypeToSave = "SICK";
      } else if (["spl", "special"].includes(rawS)) {
        statusToSave = "special";
        attendanceStatusToSave = "LEAVE";
        leaveTypeToSave = "SPECIAL";
      } else if (["absent", "a"].includes(rawS)) {
        statusToSave = "absent";
        attendanceStatusToSave = "ABSENT";
        leaveTypeToSave = null;
      }

      // Enforce annual leave quota limits (CL max 12, SL max 15 days)
      if (leaveTypeToSave === "CASUAL" && dates.length > leaveQuota.clRemaining) {
        toast.error(`Cannot request ${dates.length} day(s) of Casual Leave. You only have ${leaveQuota.clRemaining} day(s) remaining of your 12-day annual quota.`);
        return null;
      }
      if (leaveTypeToSave === "SICK" && dates.length > leaveQuota.slDaysRemaining) {
        toast.error(`Cannot request ${dates.length} day(s) of Sick Leave. You only have ${leaveQuota.slDaysRemaining} day(s) remaining of your 15-day annual quota.`);
        return null;
      }

      const successfulRecords = [];
      const skippedDates = [];

      for (const d of dates) {
        const normalizedDate = normalizeDate(d);
        if (!normalizedDate || normalizedDate > today) {
          skippedDates.push(d);
          continue;
        }
        if (holidays.has(normalizedDate)) {
          skippedDates.push(d);
          continue;
        }
        if (effectiveStartDate && normalizedDate < effectiveStartDate) {
          skippedDates.push(d);
          continue;
        }

        let existing = normalized.byDate.get(normalizedDate);
        // Query DB if not in local month state to respect unique index idx_user_batch_date
        if (!existing) {
          try {
            existing = await newAttendanceService.getAttendanceByDate(profile?.userId, resolvedBatchId, normalizedDate);
          } catch {
            existing = null;
          }
        }
        if (existing && !existing.autoGenerated) {
          if (existing.verificationStatus === "PENDING" || existing.verificationStatus === "REJECTED") {
            skippedDates.push(d);
            continue;
          }
          if (existing.status === statusToSave && existing.verificationStatus === "VERIFIED") {
            skippedDates.push(d);
            continue;
          }
        }

        const isPastDate = normalizedDate < today;
        const targetVerificationStatus = isPastDate ? "PENDING" : "VERIFIED";

        try {
          let res;
          if (existing) {
            res = await newAttendanceService.updateAttendance(existing.$id, {
              status: statusToSave,
              attendanceStatus: attendanceStatusToSave,
              leaveType: leaveTypeToSave,
              remarks,
              markedBy: profile?.userId,
              verificationStatus: targetVerificationStatus,
              rejectionReason: null,
            });
          } else {
            res = await newAttendanceService.createAttendance({
              userId: profile?.userId,
              batchId: resolvedBatchId,
              tradeId: profile?.tradeId || null,
              date: normalizedDate,
              status: statusToSave,
              attendanceStatus: attendanceStatusToSave,
              leaveType: leaveTypeToSave,
              remarks,
              markedBy: profile?.userId,
              verificationStatus: targetVerificationStatus,
              rejectionReason: null,
            });
          }

          successfulRecords.push({
            ...(res || {}),
            date: normalizedDate,
            status: statusToSave,
            attendanceStatus: attendanceStatusToSave,
            leaveType: leaveTypeToSave,
            remarks,
            markedBy: profile?.userId,
            verificationStatus: targetVerificationStatus,
            markedAt: res?.markedAt || new Date().toISOString(),
          });
        } catch (err) {
          console.error(`Error saving attendance for ${normalizedDate}:`, err);
        }
      }

      if (successfulRecords.length > 0) {
        setRawMonthlyRecords((prev) => {
          const next = Array.isArray(prev) ? [...prev] : [];
          successfulRecords.forEach((item) => {
            const idx = next.findIndex((r) => normalizeDate(r?.date) === item.date);
            if (idx >= 0) next[idx] = { ...next[idx], ...item };
            else next.push(item);
          });
          return next;
        });

        toast.success(
          `Submitted ${successfulRecords.length} past attendance request(s) for instructor verification!`
        );
        fetchAnnualLeaves();
      }

      if (skippedDates.length > 0 && successfulRecords.length === 0) {
        toast.info("Selected dates were skipped (already pending/verified, or on a holiday).");
      }

      return successfulRecords;
    } catch (error) {
      console.error("Error in markMultipleAttendance:", error);
      toast.error("Failed to submit past attendance requests.");
      throw error;
    }
  };

  return {
    isLoadingAttendance: isLoadingAttendance || isResolvingBatch || isLoadingEnrollment,
    isLoadingOverallStats,
    batchData,
    tradeData,
    studentAttendance,
    holidays,
    workingDays: finalAttendanceMap,
    finalAttendanceMap,
    finalAttendanceRecords,
    workingDaysList,
    attendanceByDate: finalAttendanceMap,
    // Raw DB records keyed by date — includes Sundays, 2nd/4th Saturdays etc.
    // Used by the calendar to display records on non-working days without
    // affecting stats which are calculated from finalAttendanceMap only.
    rawAttendanceByDate: normalized.byDate,
    attendanceStats: stats,
    monthlyStats: stats,
    overallStats,
    leaveQuota,
    currentMonth,
    selectedDate,
    setSelectedDate,
    handleMonthChange: (dateOrStr) => {
      const month =
        typeof dateOrStr === "string"
          ? dateOrStr
          : format(dateOrStr, "MMMM yyyy");
      setCurrentMonth(month);
      if (typeof dateOrStr !== "string") setSelectedDate(dateOrStr);
    },
    markAttendance,
    markMultipleAttendance,
    lastUpdatedDate,
    invalidRecords,
    enrollmentDate,
  };
};

